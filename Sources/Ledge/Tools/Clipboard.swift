import AppKit
import SwiftUI

/// The last things you copied. Kept in memory only, since clipboards carry private things.
@Observable @MainActor
final class ClipboardHistory {
    enum Item: Equatable {
        case text(String)
        case image(NSImage)
    }

    struct Entry: Identifiable {
        let id = UUID()
        let item: Item
        let copiedAt: Date
    }

    /// Password managers mark secrets with these types so clipboard tools leave them alone
    /// (the nspasteboard.org convention).
    static let skippedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    static let limit = 30

    private(set) var entries: [Entry] = []
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    func start() {
        guard timer == nil else { return }
        changeCount = NSPasteboard.general.changeCount
        // macOS has no clipboard-changed notification; checking a counter twice a second is the standard way.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        entries = []
    }

    func copy(_ entry: Entry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.item {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        }
        changeCount = pasteboard.changeCount
        insert(entry.item)
    }

    func clear() {
        entries = []
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard let types = pasteboard.types, !types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) else { return }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(.text(text))
        } else if let image = NSImage(pasteboard: pasteboard) {
            insert(.image(image))
        }
    }

    func insert(_ item: Item) {
        entries.removeAll { $0.item == item }
        entries.insert(Entry(item: item, copiedAt: .now), at: 0)
        if entries.count > Self.limit { entries.removeLast(entries.count - Self.limit) }
    }
}

struct ClipboardView: View {
    let history: ClipboardHistory
    @State private var copied: UUID?

    var body: some View {
        if history.entries.isEmpty {
            EmptyTab(title: "Nothing copied yet", hint: "Text and images you copy show up here. Click one to copy it again.")
        } else {
            VStack(alignment: .leading, spacing: 8) {
                HStack {
                    Text("Click to copy again").foregroundStyle(Palette.graphite)
                    Spacer()
                    Button("Clear") { withAnimation(Motion.easeOut(0.2)) { history.clear() } }
                        .buttonStyle(.plain)
                        .foregroundStyle(Palette.ash)
                }
                .font(Typeface.caption)
                ScrollView(showsIndicators: false) {
                    VStack(spacing: 2) {
                        ForEach(history.entries) { entry in
                            ClipRow(entry: entry, copied: copied == entry.id) {
                                history.copy(entry)
                                copied = history.entries.first?.id
                                Task {
                                    try? await Task.sleep(for: .seconds(1.2))
                                    copied = nil
                                }
                            }
                        }
                    }
                }
                .frame(height: CGFloat(min(history.entries.count, 5)) * 32) // up to five rows, then it scrolls
            }
        }
    }
}

private struct ClipRow: View {
    let entry: ClipboardHistory.Entry
    let copied: Bool
    let action: () -> Void
    @State private var hovering = false

    var body: some View {
        Button(action: action) {
            HStack(spacing: 10) {
                switch entry.item {
                case .text(let text):
                    Text(text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " "))
                        .foregroundStyle(Palette.paper)
                case .image(let image):
                    Artwork(image: image, size: 22, radius: 4)
                    Text("Image").foregroundStyle(Palette.paper)
                }
                Spacer(minLength: 8)
                Text(copied ? "Copied" : entry.copiedAt.formatted(.relative(presentation: .named, unitsStyle: .abbreviated)))
                    .foregroundStyle(copied ? Palette.paper : Palette.ash)
                    .contentTransition(.opacity)
            }
            .font(Typeface.row)
            .lineLimit(1)
            .padding(.horizontal, 10)
            .frame(height: 30)
            .background(RoundedRectangle(cornerRadius: 8, style: .continuous).fill(Palette.rail).opacity(hovering ? 1 : 0))
            .contentShape(Rectangle())
        }
        .buttonStyle(PressStyle())
        .onHover { hovering = $0 }
        .animation(Motion.ease(0.15), value: hovering)
        .animation(Motion.easeOut(0.2), value: copied)
    }
}
